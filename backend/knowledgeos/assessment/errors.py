"""Layer 4 boundary errors.

Every rejection names what was wrong and, where possible, what was expected. A validator that
says only "invalid" forces the user to guess, and this boundary is crossed by copy-paste — the
most error-prone step in the whole flow.
"""

from __future__ import annotations

from uuid import UUID


class AssessmentError(Exception):
    """Base class for every Layer 4 failure."""


class SchemaValidationError(AssessmentError):
    """A payload did not satisfy its schema. Reports every problem, not just the first."""

    def __init__(self, problems: list[str]) -> None:
        self.problems = list(problems)
        count = len(self.problems)
        noun = "problem" if count == 1 else "problems"
        detail = "\n".join(f"  - {problem}" for problem in self.problems)
        super().__init__(f"Schema B rejected ({count} {noun}):\n{detail}")


class SessionMismatchError(AssessmentError):
    """The Schema B does not belong to the session it claims to answer.

    Almost always a paste of the wrong block. Caught here because accepting it would attribute
    one concept's evidence to another — silently corrupting two nodes at once.
    """

    def __init__(self, *, field: str, expected: object, received: object) -> None:
        self.field = field
        self.expected = expected
        self.received = received
        super().__init__(
            f"Schema B {field} does not match the open session: "
            f"expected {expected!r}, received {received!r}"
        )


class UnknownSessionError(AssessmentError):
    """No open session with this id.

    Either the Schema A was never generated by this application, or the session was already
    completed — history is append-only, so a session is ingested exactly once.
    """

    def __init__(self, session_id: UUID) -> None:
        self.session_id = session_id
        super().__init__(
            f"no open session {session_id}; it was never generated here, or already ingested"
        )


class UnknownNodeReferenceError(AssessmentError):
    """A payload referenced node ids that are not in the curriculum."""

    def __init__(self, field: str, node_ids: list[str]) -> None:
        self.field = field
        self.node_ids = list(node_ids)
        joined = ", ".join(repr(n) for n in sorted(self.node_ids))
        super().__init__(f"{field} references unknown node(s): {joined}")
