"""One error contract for the whole API.

Every failure comes back in the same envelope, so a client never has to guess whether an error
is a string, a list, or FastAPI's default `{"detail": ...}`:

    {"error": {"type": "SessionMismatchError", "message": "...", "problems": [...]}}

The `problems` array matters for Schema B. Validation collects every violation rather than
stopping at the first, and a paste-driven boundary is exactly where a user wants all of them at
once instead of fixing one, re-pasting, and discovering the next.
"""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse

from knowledgeos.assessment import (
    AssessmentError,
    SchemaValidationError,
    SessionMismatchError,
    UnknownNodeReferenceError,
    UnknownSessionError,
)
from knowledgeos.curriculum import CurriculumError, NodeNotFoundError, RoleNotFoundError
from knowledgeos.state import StateError, UnknownNodeError


def error_body(exc: Exception, **extra: Any) -> dict[str, Any]:
    body: dict[str, Any] = {"type": type(exc).__name__, "message": str(exc)}
    body.update({key: value for key, value in extra.items() if value is not None})
    return {"error": body}


def register_error_handlers(app: FastAPI) -> None:
    """Map domain exceptions to status codes, keeping the envelope identical."""

    @app.exception_handler(NodeNotFoundError)
    @app.exception_handler(RoleNotFoundError)
    @app.exception_handler(UnknownNodeError)
    async def _not_found(request: Request, exc: Exception) -> JSONResponse:
        return JSONResponse(
            status_code=status.HTTP_404_NOT_FOUND, content=error_body(exc))

    @app.exception_handler(UnknownSessionError)
    async def _unknown_session(request: Request, exc: UnknownSessionError) -> JSONResponse:
        # 404: the session genuinely is not here - either never generated by this
        # application, or already ingested (history is append-only, so exactly once).
        return JSONResponse(
            status_code=status.HTTP_404_NOT_FOUND,
            content=error_body(exc, session_id=str(exc.session_id)),
        )

    @app.exception_handler(SchemaValidationError)
    async def _schema_invalid(request: Request, exc: SchemaValidationError) -> JSONResponse:
        return JSONResponse(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            content=error_body(exc, problems=exc.problems),
        )

    @app.exception_handler(SessionMismatchError)
    async def _mismatch(request: Request, exc: SessionMismatchError) -> JSONResponse:
        return JSONResponse(
            status_code=status.HTTP_409_CONFLICT,
            content=error_body(
                exc, field=exc.field, expected=str(exc.expected), received=str(exc.received)
            ),
        )

    @app.exception_handler(UnknownNodeReferenceError)
    async def _unknown_reference(
        request: Request, exc: UnknownNodeReferenceError
    ) -> JSONResponse:
        return JSONResponse(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            content=error_body(exc, field=exc.field, node_ids=exc.node_ids),
        )

    @app.exception_handler(RequestValidationError)
    async def _request_invalid(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        problems = [
            f"{'.'.join(str(p) for p in error['loc'])}: {error['msg']}"
            for error in exc.errors()
        ]
        return JSONResponse(
            status_code=status.HTTP_422_UNPROCESSABLE_CONTENT,
            content={
                "error": {
                    "type": "RequestValidationError",
                    "message": "request body failed validation",
                    "problems": problems,
                }
            },
        )

    @app.exception_handler(AssessmentError)
    @app.exception_handler(CurriculumError)
    @app.exception_handler(StateError)
    async def _domain_error(request: Request, exc: Exception) -> JSONResponse:
        return JSONResponse(
            status_code=status.HTTP_400_BAD_REQUEST, content=error_body(exc))
